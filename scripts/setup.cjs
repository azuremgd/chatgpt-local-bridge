const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { validateRoot, within } = require('../core.cjs');
const { publicOrigin, assertDevSpaceVersion } = require('../installation.cjs');
const { secureRuntime } = require('../runtime-security.cjs');

function prepare(input, home = os.homedir()) {
  if (process.platform !== 'win32') throw Error('This release supports Windows only.');
  const origin = publicOrigin(input.publicUrl);
  const runtime = path.resolve(input.runtime);
  const source = path.resolve(__dirname, '..');
  if (!path.isAbsolute(input.runtime) || within(source, runtime) || within(runtime, source) || within(runtime, home)) throw Error('Runtime must be a dedicated directory outside the source checkout and user home root.');
  const realParent = fs.realpathSync.native(path.dirname(runtime));
  const actualRuntime = path.join(realParent, path.basename(runtime));
  if (within(source, actualRuntime) || within(actualRuntime, source) || within(actualRuntime, home)) throw Error('Runtime resolves to a protected directory.');
  if (fs.existsSync(runtime) && fs.lstatSync(runtime).isSymbolicLink()) throw Error('Runtime cannot be a junction or symbolic link.');
  if (!Number.isInteger(input.port) || input.port < 1024 || input.port > 65535) throw Error('Port must be between 1024 and 65535.');
  if (!/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i.test(input.tunnelId)) throw Error('Supply the named tunnel UUID, not a token.');
  for (const key of ['nodePath','devspaceCliPath','cloudflaredPath','bashDirectory','credentialsFile']) {
    if (!path.isAbsolute(input[key] || '') || !fs.existsSync(input[key])) throw Error(`Missing installation file: ${key}`);
  }
  assertDevSpaceVersion(input.devspaceCliPath);
  if (within(source, fs.realpathSync.native(input.credentialsFile))) throw Error('Keep Cloudflare credentials outside the source checkout.');
  if (typeof input.ownerPassword !== 'string' || input.ownerPassword.length < 24) throw Error('Use an Owner Password with at least 24 characters, preferably generated by a password manager.');
  const files = ['bridge-settings.json','config/config.json','config/auth.json','cloudflared/config.yml'];
  if (files.some(file => fs.existsSync(path.join(runtime,file)))) throw Error('An installation already exists here; refusing to overwrite configuration or credentials.');
  const workspace = input.projectDirectory ? fs.realpathSync.native(input.projectDirectory) : path.join(runtime,'workspace');
  validateRoot(workspace, [], home, p => p, [path.join(runtime,'config'),path.join(runtime,'state'),path.join(runtime,'logs'),path.join(runtime,'cloudflared'),path.join(runtime,'bridge-settings.json'),input.credentialsFile]);
  if (input.projectDirectory && !fs.statSync(workspace).isDirectory()) throw Error('Project must be a directory.');
  const config = {
    host:'127.0.0.1', port:input.port, allowedRoots:[workspace], publicBaseUrl:origin,
    allowedHosts:[new URL(origin).hostname], subagents:{enabled:false,providers:[]}, artifactsEnabled:false,
    stateDir:path.join(runtime,'state','devspace'), worktreeRoot:path.join(runtime,'worktrees'), agentDir:path.join(runtime,'disabled-agents')
  };
  const settings = {schemaVersion:1,nodePath:input.nodePath,devspaceCliPath:input.devspaceCliPath,cloudflaredPath:input.cloudflaredPath,bashDirectory:input.bashDirectory,tunnelName:input.tunnelId};
  const tunnel = `tunnel: ${JSON.stringify(input.tunnelId)}\ncredentials-file: ${JSON.stringify(input.credentialsFile)}\ningress:\n  - hostname: ${JSON.stringify(new URL(origin).hostname)}\n    service: http://127.0.0.1:${input.port}\n  - service: http_status:404\n`;
  return {runtime,workspace,config,settings,tunnel};
}
function install(input, home = os.homedir()) {
  const prepared = prepare(input, home);
  secureRuntime(prepared.runtime, true);
  for (const dir of ['config','cloudflared','state','logs','workspace']) fs.mkdirSync(path.join(prepared.runtime,dir),{recursive:true});
  const write = (name,value) => fs.writeFileSync(path.join(prepared.runtime,name),typeof value === 'string' ? value : JSON.stringify(value,null,2)+'\n',{flag:'wx',mode:0o600});
  write('config/config.json',prepared.config);
  write('config/auth.json',{ownerToken:input.ownerPassword});
  write('cloudflared/config.yml',prepared.tunnel);
  write('bridge-settings.json',prepared.settings);
  return {message:'Configuration created. Owner Password was not printed. Complete the DNS route, then open the console.',mcpUrl:prepared.config.publicBaseUrl+'/mcp'};
}
if (require.main === module) {
  let data='';
  process.stdin.setEncoding('utf8');
  process.stdin.on('data',chunk=>{data+=chunk;if(data.length>65536){console.error('Input too large.');process.exit(1);}});
  process.stdin.on('end',()=>{
    try { const result=install(JSON.parse(data.replace(/^\uFEFF/,''))); data=''; console.log(JSON.stringify(result)); }
    catch(error){console.error(error.message);process.exitCode=1;}
  });
}
module.exports={prepare,install};
